import 'package:equatable/equatable.dart';

import 'category_stat.dart';
import 'item_stat.dart';
import 'stats_period.dart';
import 'time_bucket.dart';

/// Complete immutable calculation model presenting waste statistics for the UI.
/// Produced purely by [StatsCalculator].
class StatsSummary extends Equatable {
  const StatsSummary({
    required this.period,
    required this.totalEvents,
    required this.rescuedUnits,
    required this.usedLateUnits,
    required this.wastedUnits,
    required this.wasteRate,
    required this.valueUsedPaise,
    required this.usedPricedUnits,
    required this.valueWastedPaise,
    required this.wastedPricedUnits,
    required this.daysSinceLastWaste,
    required this.timeBuckets,
    required this.categoryBreakdown,
    required this.topWastedItems,
    required this.topUsedItems,
    this.insight,
  });

  /// The active evaluation time window.
  final StatsPeriod period;

  /// Total non-deleted events logged during the period.
  final int totalEvents;

  /// Items used on or before their local expiry date (end of that day).
  final int rescuedUnits;

  /// Items consumed after their expiry date passed.
  final int usedLateUnits;

  /// Total units consumed (rescuedUnits + usedLateUnits).
  int get totalUsedUnits => rescuedUnits + usedLateUnits;

  /// Total units thrown away during the period.
  final int wastedUnits;

  /// Waste rate = wastedUnits / (totalUsedUnits + wastedUnits).
  /// Null if denominator is 0 (UI shows "No data yet").
  final double? wasteRate;

  /// Total value in paise of used items that had a recorded price.
  final int valueUsedPaise;

  /// Units of used items that contributed to [valueUsedPaise].
  final int usedPricedUnits;

  /// Total value in paise of wasted items that had a recorded price.
  final int valueWastedPaise;

  /// Units of wasted items that contributed to [valueWastedPaise].
  final int wastedPricedUnits;

  /// Whole days since the most recent wasted event (all time up to now).
  /// Null if no item was ever wasted.
  final int? daysSinceLastWaste;

  /// Continuous chronological bar chart buckets for Chart 1.
  final List<TimeBucket> timeBuckets;

  /// Wasted units and value grouped by category for Chart 2.
  final List<CategoryStat> categoryBreakdown;

  /// Top 5 wasted items by units, grouped by normalized name.
  final List<ItemStat> topWastedItems;

  /// Top 5 used items by units, grouped by normalized name.
  final List<ItemStat> topUsedItems;

  /// Optional rule-based insight generated by [InsightGenerator].
  final String? insight;

  /// Coverage notes for value reporting:
  /// "Based on X of Y items with a price".
  String get usedCoverageNote {
    if (totalUsedUnits == 0) return 'No items consumed';
    return 'Based on $usedPricedUnits of $totalUsedUnits items with a price';
  }

  String get wastedCoverageNote {
    if (wastedUnits == 0) return 'No items wasted';
    return 'Based on $wastedPricedUnits of $wastedUnits items with a price';
  }

  /// Whether there are zero non-deleted events in this period.
  bool get isEmpty => totalEvents == 0;

  @override
  List<Object?> get props => [
        period,
        totalEvents,
        rescuedUnits,
        usedLateUnits,
        wastedUnits,
        wasteRate,
        valueUsedPaise,
        usedPricedUnits,
        valueWastedPaise,
        wastedPricedUnits,
        daysSinceLastWaste,
        timeBuckets,
        categoryBreakdown,
        topWastedItems,
        topUsedItems,
        insight,
      ];
}

